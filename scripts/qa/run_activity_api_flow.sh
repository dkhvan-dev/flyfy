}

activity_payload() {
  local title="$1"
  local start="$2"
  local end="$3"
  local category="${4:-food-drinks}"
  local subcategory="${5:-coffee-meetup}"
  local format="${6:-OFFLINE}"
  local visibility="${7:-PUBLIC}"
  local price_type="${8:-FREE}"
  local max_participants="10"
  local extra="{}"

  if [[ $# -ge 9 ]]; then
    max_participants="$9"
  fi
  if [[ $# -ge 10 ]]; then
    extra="${10}"
  fi

  if ! printf "%s" "$extra" | jq -e . >/dev/null 2>&1; then
    echo "Invalid extra JSON for activity payload: $extra" >&2
    extra="{}"
  fi

  jq -n \
    --arg title "$title" \
    --arg description "Autogenerated QA activity for flow coverage." \
    --arg format "$format" \
    --arg visibility "$visibility" \
    --arg category "$category" \
    --arg subcategory "$subcategory" \
    --arg start "$start" \
    --arg end "$end" \
    --arg priceType "$price_type" \
    --arg country "KZ" \
    --arg city "Алматы" \
    --arg address "QA street 1" \
    --arg map "https://maps.google.com/?q=43.238949,76.889709" \
    --arg maxParticipants "$max_participants" \
    --arg extra "$extra" \
    '{
      title: $title,
      description: $description,
      format: $format,
      visibility: $visibility,
      categorySlug: $category,
      subcategorySlug: $subcategory,
      tags: ["qa", "activity-flow"],
      languageCode: "ru",
      timezone: "Asia/Almaty",
      startAt: $start,
      endAt: $end,
      capacityType: "LIMITED",
      minParticipants: 2,
      maxParticipants: ($maxParticipants | tonumber),
      priceType: $priceType,
      requiresProfileCompletion: false,
      requiresAttendanceConfirmation: false,
      allowsParticipantInvites: false,
      countryCode: $country,
      cityName: $city,
      addressText: $address,
      latitude: 43.238949,
      longitude: 76.889709,
      mapUrl: $map,
      authorCountryCode: $country,
      authorCityName: $city
    } * ($extra | fromjson)'
}

