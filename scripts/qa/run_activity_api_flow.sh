psql_activity() {
  docker exec activity-postgres psql -q -U activity_service -d activity_service_db -c "$1" >/dev/null 2>&1 || true
}

reset_qa_rate_limit_window() {
  psql_activity "update activities set created_at = now() - interval '48 hours' where title like 'QA %' and created_at > now() - interval '24 hours';"
}

cleanup_previous_qa_state() {
  psql_activity "update activity_participants p set status = 'CANCELLED', cancelled_at = coalesce(cancelled_at, now()), updated_at = now() from activities a where p.activity_id = a.id and a.title like 'QA %' and p.status in ('INVITED','REQUESTED','APPROVED','WAITLISTED','PENDING_PAYMENT','CONFIRMED','CHECKED_IN');"
  psql_activity "update activities set status = 'CANCELLED', cancellation_reason = coalesce(cancellation_reason, 'QA cleanup before activity flow suite'), cancelled_at = coalesce(cancelled_at, now()), updated_at = now(), created_at = now() - interval '48 hours' where title like 'QA %';"
  reset_qa_rate_limit_window
}

req() {
  local method="$1"
  local path="$2"
  local token="${3:-}"
  local data="${4:-}"
  local body="$TMP_DIR/body.json"
  local code
  : > "$body"

  if [[ -n "$data" ]]; then
    if [[ -n "$token" ]]; then
      code=$(curl -s -o "$body" -w "%{http_code}" -X "$method" "$BASE$path" \
        -H "Content-Type: application/json" \
        -H "Authorization: Bearer $token" \
        -d "$data" || printf "000")
    else
      code=$(curl -s -o "$body" -w "%{http_code}" -X "$method" "$BASE$path" \
        -H "Content-Type: application/json" \
        -d "$data" || printf "000")
    fi
  else
    if [[ -n "$token" ]]; then
      code=$(curl -s -o "$body" -w "%{http_code}" -X "$method" "$BASE$path" \
        -H "Authorization: Bearer $token" || printf "000")
    else
      code=$(curl -s -o "$body" -w "%{http_code}" -X "$method" "$BASE$path" || printf "000")
    fi
  fi

  printf "%s\n" "$code" > "$TMP_DIR/last_code"
  cp "$body" "$TMP_DIR/last_body.json"
}

body_excerpt() {
  tr "\n" " " < "$TMP_DIR/last_body.json" | cut -c1-220
}

record() {
  local id="$1"
  local result="$2"
  local actual="$3"
  printf "%s\t%s\t%s\n" "$id" "$result" "$actual" >> "$RESULTS"
}

expect_code() {
  local id="$1"
  local expected="$2"
  local actual_code
  actual_code=$(cat "$TMP_DIR/last_code")
  if [[ "$actual_code" == "$expected" ]]; then
    record "$id" "PASS" "HTTP $actual_code"
  else
    record "$id" "FAIL" "Expected HTTP $expected, got $actual_code; body=$(body_excerpt)"
  fi
}

expect_code_any() {
  local id="$1"
  local expected_csv="$2"
  local actual_code
  actual_code=$(cat "$TMP_DIR/last_code")
  if [[ ",$expected_csv," == *",$actual_code,"* ]]; then
    record "$id" "PASS" "HTTP $actual_code"
  else
    record "$id" "FAIL" "Expected one of [$expected_csv], got $actual_code; body=$(body_excerpt)"
  fi
}

auth() {
  local phone="$1"
  local token
  req POST "/auth/phone/send-code" "" "{\"phone\":\"$phone\"}"
  req POST "/auth/phone/verify" "" "{\"phone\":\"$phone\",\"code\":\"000000\"}"
  token=$(jq -r ".access_token // .accessToken // empty" "$TMP_DIR/last_body.json")
  if [[ -z "$token" ]]; then
    echo "AUTH_FAILED for $phone" >&2
    cat "$TMP_DIR/last_body.json" >&2
    exit 1
  fi
  printf "%s" "$token"
}

uri() {
