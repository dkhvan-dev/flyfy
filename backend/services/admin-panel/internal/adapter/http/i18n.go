func localeURL(path string, locale string) string {
	if strings.TrimSpace(path) == "" {
		path = "/admin"
	}
	query := url.Values{}
	query.Set("lang", locale)
	return path + "?" + query.Encode()
}

func toString(value any) string {
	switch typed := value.(type) {
	case string:
		return typed
	default:
		return fmt.Sprint(value)
	}
}
