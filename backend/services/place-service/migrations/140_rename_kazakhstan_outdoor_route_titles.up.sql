SET
    title = readable.new_title,
    updated_at = NOW()
FROM places p
JOIN seed_kazakhstan_outdoor_route_titles readable
    ON p.tags @> ARRAY[readable.slug]::text[]
WHERE pt.place_id = p.id
  AND pt.locale = 'ru'
  AND p.country_code = 'KZ'
  AND pt.title <> readable.new_title;

