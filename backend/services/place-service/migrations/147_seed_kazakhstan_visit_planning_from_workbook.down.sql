WITH matched_places AS (
    SELECT DISTINCT p.id AS place_id
    FROM seed_kazakhstan_visit_planning_rollback seed
    JOIN place_translations pt
      ON pt.locale = 'ru'
     AND pt.title = seed.title_ru
    JOIN places p
      ON p.id = pt.place_id
     AND p.country_code = 'KZ'
)
UPDATE places p
SET
    visit_info = COALESCE(p.visit_info, '{}'::jsonb)
        - 'feeItems'
        - 'accessOptions'
        - 'practicalNotes'
        - 'recommendedItems'
        - 'priceNote'
        - 'timeOnSite'
        - 'carTravelTime'
        - 'roadCondition'
        - 'lastVerifiedAt',
    updated_at = NOW()
FROM matched_places m
WHERE p.id = m.place_id;

